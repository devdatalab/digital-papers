<!--
	NobelRankScatter — the title page's primary data visualization.

	A jittered 2D scatter: each dot is one laureate-prize row, placed by prize
	year (x) and a father-background percentile rank (y). Dots are coloured by
	prize category and the legend filters categories.

	It is driven from outside by the title page's scrollytelling
	(LandingScrolly.svelte), so presentation is controlled through props:
	  - `metric` (bindable): active y-axis metric; the pill selector writes it.
	  - `metricKeys` / `metricLabels`: which metrics the pills offer, and their
	    short labels. Defaults to every metric in the dataset, so metrics hidden on
	    the title page (education, prestige) come back by passing more keys.
	  - `colorMode`: 'none' (uniform grey) or 'category' (field colours).
	  - `focusId`: spotlight and label one row; everything else dims.
	  - `focusCard`: open the focused row's laureate card (in place of its
	    label) without a click, so the scrolly can show what clicking does
	    before the chart is interactive.
	  - `controls`: toolbar state — hidden, legend only, pills shown but locked to
	    the scroll ('display'), or fully reader-operable ('interactive'). Hover
	    tooltips, the laureate card and legend filtering work from the legend
	    step onward; only metric selection waits for the interactive step.
	  - `fill`: take the height of a flex parent (the pinned scrolly frame)
	    instead of the fixed `height`.
	State changes animate (dots glide between metrics, colours cross-fade) unless
	the reader prefers reduced motion.

	Laureate card: clicking (or tapping) a dot pins the tooltip open as a card
	with the laureate's portrait, a Wikipedia link and the photo credit. Links
	come from laureate_links.json, loaded lazily on first interaction so it
	stays out of the title page's initial bundle; portraits are hotlinked from
	Wikimedia Commons and fetched only for the card being opened. Escape, the
	close button, or a click elsewhere dismisses it. (ddl-charts' tooltip is
	hover-only with pointer-events off; a "pinnable" option upstream would let
	other charts do this without the local toggling below.)

	Why a custom chart: ddl-charts ships a 1D beeswarm, not a 2D year×rank
	scatter, so this composes ddl-charts' core primitives (container, scales,
	axes, colours, legend, tooltip, nearest-point hit testing, utils) and adds
	only the scatter glue, the deterministic jitter, and the laureate tooltip.

	Upstream dependencies:
	  - $nobel/data (typed dataset from scripts/site-data/generators/extract_viz_data/, and
	    loadLaureateLinks() over scripts/laureate-links/laureate_links.py output)
	  - @devdatalab/ddl-charts (core/components primitives)
	  - d3 (selections, transitions, formatting, pointer)
-->
<script lang="ts">
	import { onMount } from 'svelte';
	import * as d3 from 'd3';
	import {
		createContainer,
		createLinearScale,
		createXAxis,
		createYAxis,
		createTooltip,
		showTooltip,
		hideTooltip,
		positionTooltip,
		createLegend,
		updateLegendVisibility,
		nearestPoint,
		formatNumber,
		MUTED_COLORS,
		UI_COLORS
	} from '@devdatalab/ddl-charts';
	import {
		nobelRows as rows,
		nobelMetrics as metrics,
		loadLaureateLinks,
		type NobelRow,
		type Metric,
		type LaureateLink,
		PRIZE_CATEGORIES
	} from '$nobel/data';

	type ColorMode = 'none' | 'category';
	type Controls = 'hidden' | 'legend' | 'display' | 'interactive';

	// The dataset is a static, import-time module (generated by
	// scripts/site-data/generators/extract_viz_data/), so it is imported directly rather
	// than passed as props. Only presentation is configurable.
	let {
		height = 480,
		fill = false,
		metricKeys = metrics.map((m) => m.key),
		metricLabels = {},
		metric = $bindable(metricKeys[0] ?? metrics[0]?.key ?? ''),
		colorMode = 'category',
		focusId = null,
		focusCard = false,
		highlightFrom = null,
		controls = 'interactive'
	}: {
		height?: number;
		fill?: boolean;
		metricKeys?: string[];
		metricLabels?: Record<string, string>;
		metric?: string;
		colorMode?: ColorMode;
		focusId?: number | null;
		focusCard?: boolean;
		/** Optional lower bound of a shaded rank band, ending at 100. */
		highlightFrom?: number | null;
		controls?: Controls;
	} = $props();

	const metricOptions = $derived(
		metricKeys
			.map((k) => metrics.find((m) => m.key === k))
			.filter((m): m is Metric => m != null)
	);
	const interactive = $derived(controls !== 'hidden');
	const metricInteractive = $derived(controls === 'interactive');

	// Colourblind-safe (Okabe-Ito) colours, one per prize category. Yellow is
	// omitted as it reads poorly on a white background.
	const CATEGORY_COLOR: Record<string, string> = {
		Physics: '#0072B2',
		Chemistry: '#009E73',
		Medicine: '#D55E00',
		Economics: '#CC79A7'
	};
	const colorFor = (cat: string) => CATEGORY_COLOR[cat] ?? UI_COLORS.text;
	// Uncoloured dots before the scrolly introduces the field colours.
	const NEUTRAL_DOT = '#8d939c';

	/** One positioned dot: a source row plus its SVG coordinates. */
	type Pt = { row: NobelRow; x: number; y: number };

	/** Everything the imperative chart needs from the props. */
	type ChartState = {
		metric: string;
		colorMode: ColorMode;
		focusId: number | null;
		focusCard: boolean;
		highlightFrom: number | null;
		interactive: boolean;
	};

	let host: HTMLDivElement;
	let legendHost: HTMLDivElement;

	// Imperative chart handle, set on mount. $state.raw so the effect below
	// re-runs once it exists, without Svelte proxying the object.
	let chart = $state.raw<{ update: (s: ChartState) => void } | null>(null);

	// Push prop changes into the D3 chart.
	$effect(() => {
		const s: ChartState = { metric, colorMode, focusId, focusCard, highlightFrom, interactive };
		chart?.update(s);
	});

	function pickMetric(key: string) {
		if (metricInteractive) metric = key;
	}

	// Deterministic [-1, 1) hash from a stable id, so horizontal jitter is
	// identical across reloads, SSR, and re-renders (no Math.random).
	function jitterFrac(id: number): number {
		const x = Math.sin(id * 127.1 + 311.7) * 43758.5453;
		return (x - Math.floor(x)) * 2 - 1;
	}

	function esc(s: unknown): string {
		return String(s ?? '').replace(
			/[&<>"]/g,
			(c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c] as string
		);
	}

	onMount(() => {
		const years = rows.map((r) => r.year).filter((y) => Number.isFinite(y));
		const yearMin = Math.min(...years);
		const yearMax = Math.max(...years);
		const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)');

		// Current chart state; replaced wholesale by update().
		let cur: ChartState = { metric, colorMode, focusId, focusCard, highlightFrom, interactive };
		let activeMetric: Metric = metrics.find((m) => m.key === cur.metric) ?? metrics[0];
		const visible = new Set<string>(PRIZE_CATEGORIES);

		const syncLegend = () =>
			updateLegendVisibility(
				d3.select(legendHost),
				Object.fromEntries(PRIZE_CATEGORIES.map((c) => [c, visible.has(c)]))
			);

		// --- Category legend (click / keyboard to filter) -----------------------
		// No branded frame: the figure is bespoke, so the legend and chart are
		// built straight into the component's own host elements.
		const legendSel = createLegend(
			d3.select(legendHost),
			PRIZE_CATEGORIES.map((c) => ({ id: c, label: c, color: colorFor(c), visible: true })),
			{
				position: 'top',
				onClick: (id: string) => {
					if (!cur.interactive) return;
					if (visible.has(id)) visible.delete(id);
					else visible.add(id);
					syncLegend();
					render(true);
				}
			}
		);
		// Lay the legend out as a horizontal, wrapping row and make items
		// keyboard-operable (createLegend only wires mouse clicks).
		legendSel.style('display', 'flex').style('flex-wrap', 'wrap').style('gap', '0.25rem 0.5rem');
		const legendItems = legendSel
			.selectAll('.legend-item')
			.attr('role', 'button')
			.attr('aria-label', (d: { id: string }) => `Toggle ${d.id}`)
			.on('keydown', function (this: HTMLElement, event: KeyboardEvent) {
				if (event.key === 'Enter' || event.key === ' ') {
					event.preventDefault();
					this.click();
				}
			});
		const syncLegendFocusable = () =>
			legendItems.attr('tabindex', cur.interactive ? 0 : -1);
		syncLegendFocusable();

		// --- Responsive SVG container -------------------------------------------
		// In fill mode the host is a flex child sized by the pinned scrolly frame,
		// so its measured height wins over the `height` prop.
		const margin = { top: 16, right: 44, bottom: 60, left: 88 };
		const initialHeight = fill && host.clientHeight > 200 ? host.clientHeight : height;
		const { container, svg, chartArea, dimensions } = createContainer(d3.select(host), {
			height: initialHeight,
			margin,
			responsive: true,
			onResize: () => render(false) // createContainer only resizes the SVG; we redraw.
		});

		createTooltip(container);

		// createContainer's `responsive` mode only listens to *window* resize
		// events and only tracks width, so it misses container-size changes that
		// happen without one — e.g. navigating back to the title page, where the
		// shell switches from the three-column layout to a full-width single
		// column, or the pinned frame changing height as the mobile browser
		// toolbar shows/hides. Observe the host directly and re-fit.
		// (Upstream fix: createContainer should use a ResizeObserver and support
		// height — worth adding to ddl-charts so every chart gets this for free.)
		const resizeObserver = new ResizeObserver(() => {
			const rect = host.getBoundingClientRect();
			let changed = false;
			if (rect.width && rect.width !== dimensions.width) {
				dimensions.width = rect.width;
				dimensions.innerWidth = rect.width - margin.left - margin.right;
				svg.attr('width', rect.width);
				changed = true;
			}
			if (fill && rect.height > 200 && Math.round(rect.height) !== dimensions.height) {
				dimensions.height = Math.round(rect.height);
				dimensions.innerHeight = dimensions.height - margin.top - margin.bottom;
				svg.attr('height', dimensions.height);
				changed = true;
			}
			if (changed) render(false);
		});
		resizeObserver.observe(host);

		// Persistent layers: axes are cheap and redrawn each render; dots persist
		// so a keyed join can animate them between states.
		// Narrative band sits behind axes and dots and never captures input.
		const rankBand = chartArea.append('rect')
			.attr('fill', 'var(--accent)')
			.attr('opacity', 0)
			.style('pointer-events', 'none');
		const axesLayer = chartArea.append('g').attr('class', 'axes');
		// Typed explicitly: ddl-charts is untyped, so chartArea is `any`.
		const dotsLayer: d3.Selection<SVGGElement, unknown, null, undefined> = chartArea
			.append('g')
			.attr('class', 'dots');
		const focusLayer = chartArea.append('g').attr('class', 'focus').style('pointer-events', 'none');
		const hoverLayer = chartArea.append('g').attr('class', 'hover');

		// Per-render state used by the shared hover handler.
		let hitPoints: { id: number; x: number; y: number }[] = [];
		let dotById = new Map<number, Pt>();
		// Set once the laureate card is wired up (below); keeps a pinned card
		// attached to its dot across re-renders.
		let afterRender: () => void = () => {};

		const dotFill = (d: Pt) =>
			cur.colorMode === 'none'
				? NEUTRAL_DOT
				: visible.has(d.row.category)
					? colorFor(d.row.category)
					: MUTED_COLORS.line;
		const dotOpacity = (d: Pt) => {
			if (cur.focusId != null) return d.row.id === cur.focusId ? 1 : 0.22;
			return visible.has(d.row.category) ? 0.85 : 0.5;
		};

		function render(animate: boolean) {
			const innerWidth = dimensions.innerWidth;
			const innerHeight = dimensions.innerHeight;
			const duration = animate && !reduceMotion.matches ? 500 : 0;
			const t = d3.transition().duration(duration).ease(d3.easeCubicInOut);

			const xScale = createLinearScale({
				domain: [yearMin, yearMax],
				range: [0, innerWidth],
				padding: 0.03
			});
			const yScale = createLinearScale({ domain: [0, 100], range: [innerHeight, 0] });

			const threshold = Math.min(100, Math.max(0, cur.highlightFrom ?? 100));
			rankBand
				.attr('x', 0)
				.attr('y', yScale(100))
				.attr('width', Math.max(0, innerWidth))
				.attr('height', Math.max(0, yScale(threshold) - yScale(100)))
				.interrupt()
				.transition(t)
				.attr('opacity', cur.highlightFrom == null ? 0 : 0.08);

			axesLayer.selectAll('*').remove();
			createYAxis(axesLayer, yScale, {
				x: 0,
				grid: true,
				gridWidth: innerWidth,
				tickCount: 5,
				label: activeMetric.axisLabel
			});
			createXAxis(axesLayer, xScale, {
				y: innerHeight,
				tickFormat: d3.format('d'),
				tickCount: 8,
				label: 'Prize year'
			});

			// Spread dots within their year band so dense years stay legible.
			const halfBand = Math.max(2, (xScale(yearMin + 1) - xScale(yearMin)) * 0.42);
			const pts: Pt[] = [];
			for (const row of rows) {
				const v = row.ranks[activeMetric.key];
				if (v == null || !Number.isFinite(v)) continue;
				pts.push({
					row,
					x: xScale(row.year) + jitterFrac(row.id) * halfBand,
					y: yScale(v)
				});
			}

			// Rows without a value for the new metric fade out; rows gaining one
			// fade in at their final spot; the rest glide.
			dotsLayer
				.selectAll<SVGCircleElement, Pt>('circle')
				.data(pts, (d: Pt) => d.row.id)
				.join(
					(enter) =>
						enter
							.append('circle')
							.attr('r', 3.2)
							.attr('cx', (d) => d.x)
							.attr('cy', (d) => d.y)
							.style('stroke', 'white')
							.style('stroke-width', 0.5)
							.style('opacity', 0),
					(update) => update,
					(exit) => exit.transition(t).style('opacity', 0).remove()
				)
				.transition(t)
				.attr('cx', (d) => d.x)
				.attr('cy', (d) => d.y)
				.style('fill', dotFill)
				.style('opacity', dotOpacity);

			renderFocus(pts, innerWidth, duration);
			hoverLayer.selectAll('*').remove();

			// Hover only snaps to currently-visible dots.
			const shown = pts.filter((d) => visible.has(d.row.category));
			hitPoints = shown.map((d) => ({ id: d.row.id, x: d.x, y: d.y }));
			dotById = new Map(shown.map((d) => [d.row.id, d]));
			afterRender();
		}

		// Spotlight: a ring around the focused dot plus a two-line label with a
		// short leader, flipped left near the right edge and below near the top
		// (high-rank dots would otherwise push the label out of the SVG). With
		// `focusCard` the laureate card names the dot, so only the ring is drawn.
		function renderFocus(pts: Pt[], innerWidth: number, duration: number) {
			focusLayer.selectAll('*').remove();
			const dot = cur.focusId == null ? null : pts.find((d) => d.row.id === cur.focusId);
			if (!dot) return;
			dotsLayer
				.selectAll<SVGCircleElement, Pt>('circle')
				.filter((d) => d.row.id === dot.row.id)
				.raise();

			const flip = dot.x > innerWidth - 200;
			const below = dot.y < 60;
			const dx = flip ? -14 : 14;
			const g = focusLayer
				.append('g')
				.attr('transform', `translate(${dot.x},${dot.y})`)
				.style('opacity', 0);
			g.append('circle')
				.attr('r', 8)
				.style('fill', 'none')
				.style('stroke', 'var(--ink, #222)')
				.style('stroke-width', 1.5);
			if (cur.focusCard) {
				g.style('opacity', 1);
				return;
			}
			g.append('line')
				.attr('x1', flip ? -8 : 8)
				.attr('y1', below ? 4 : -4)
				.attr('x2', dx)
				.attr('y2', below ? 18 : -18)
				.style('stroke', 'var(--ink, #222)')
				.style('stroke-width', 1);
			const text = g
				.append('text')
				.attr('x', dx + (flip ? -4 : 4))
				.attr('y', below ? 30 : -30)
				.attr('text-anchor', flip ? 'end' : 'start')
				.style('font-family', 'var(--font-ui)')
				.style('paint-order', 'stroke')
				.style('stroke', 'var(--bg, #fff)')
				.style('stroke-width', 4)
				.style('stroke-linejoin', 'round');
			text.append('tspan').style('font-weight', 600).style('font-size', '14px').style('fill', 'var(--ink, #222)').text(dot.row.name);
			text
				.append('tspan')
				.attr('x', dx + (flip ? -4 : 4))
				.attr('dy', '1.25em')
				.style('font-size', '12px')
				.style('fill', UI_COLORS.text)
				.text(`${dot.row.category} · ${dot.row.year}`);
			g.transition()
				.delay(duration ? duration * 0.5 : 0)
				.duration(duration ? 250 : 0)
				.style('opacity', 1);
		}

		// --- Hover tooltip + pinned laureate card ---------------------------------
		// The same ddl-charts tooltip element serves both: hover fills it with a
		// summary; a click pins it as a card (pointer-events on, so its links are
		// clickable) until dismissed.
		const tooltipSel = container.select('.ddl-tooltip');
		let pinnedId: number | null = null;
		let links: Record<string, LaureateLink> | null = null;

		// Fetch the links file the first time a reader engages with the chart.
		function ensureLinks() {
			if (links) return;
			loadLaureateLinks()
				.then((l) => {
					links = l;
					// A card opened before the file arrived gets its photo/link now.
					const dot = pinnedId == null ? null : dotById.get(pinnedId);
					if (dot) showCard(dot);
				})
				.catch(() => {
					/* card just lacks photo/link; the next interaction retries */
				});
		}

		function drawRing(dot: Pt) {
			hoverLayer.selectAll('*').remove();
			hoverLayer
				.append('circle')
				.attr('cx', dot.x)
				.attr('cy', dot.y)
				.attr('r', 5.5)
				.style('fill', 'none')
				.style('stroke', colorFor(dot.row.category))
				.style('stroke-width', 2)
				.style('pointer-events', 'none');
		}

		// Shared body: name, prize line, current rank and father's occupation.
		function summaryHtml(dot: Pt): string {
			const v = dot.row.ranks[activeMetric.key];
			return (
				`<div style="font-weight:600;margin-bottom:2px;">${esc(dot.row.name)}</div>` +
				`<div style="color:${UI_COLORS.textLight};font-size:12px;margin-bottom:6px;">` +
				`${esc(dot.row.category)} · ${dot.row.year}${dot.row.country ? ' · ' + esc(dot.row.country) : ''}</div>` +
				`<div style="display:grid;grid-template-columns:auto 1fr;gap:2px 10px;font-size:12px;">` +
				`<span style="color:${UI_COLORS.textLight};">${esc(activeMetric.label)}</span>` +
				`<span>${v == null ? '—' : formatNumber(v) + 'th pctile'}</span>` +
				`<span style="color:${UI_COLORS.textLight};">Father</span>` +
				`<span>${dot.row.fatherOcc ? esc(dot.row.fatherOcc) : '—'}</span></div>`
			);
		}

		function showHover(dot: Pt) {
			drawRing(dot);
			showTooltip(
				container,
				summaryHtml(dot) + `<div class="lc-hint">Click for photo and Wikipedia link</div>`
			);
		}

		function clearHover() {
			if (pinnedId != null) return; // a pinned card outlives the pointer
			hoverLayer.selectAll('*').remove();
			svg.style('cursor', null);
			hideTooltip(container);
		}

		/** Anchor the tooltip to a dot (chart coords → container coords). */
		function placeAt(dot: Pt) {
			positionTooltip(container, dot.x + margin.left, dot.y + margin.top, {
				preferAbove: true
			});
		}

		function showCard(dot: Pt) {
			const link = links?.[String(dot.row.id)];
			const ext = `target="_blank" rel="noopener noreferrer"`;
			const photo = link?.img
				? `<div class="lc-photo"><img src="${esc(link.img)}" alt="Portrait of ${esc(dot.row.name)}"` +
					` referrerpolicy="no-referrer" decoding="async"></div>`
				: '';
			const wiki = link?.wiki
				? `<a class="lc-wiki" href="${esc(link.wiki)}" ${ext}>Read on Wikipedia <span aria-hidden="true">↗</span></a>`
				: '';
			let credit = '';
			if (link?.img) {
				const who = link.credit ? esc(link.credit) : 'Wikimedia Commons';
				const lic = link.license
					? link.licenseUrl
						? ` · <a href="${esc(link.licenseUrl)}" ${ext}>${esc(link.license)}</a>`
						: ` · ${esc(link.license)}`
					: '';
				credit =
					`<div class="lc-credit">Photo: ` +
					(link.source ? `<a href="${esc(link.source)}" ${ext}>${who}</a>` : who) +
					`${lic}</div>`;
			}
			showTooltip(
				container,
				`<button type="button" class="lc-close" aria-label="Close">×</button>` +
					`<div class="lc-top">${photo}<div class="lc-body">${summaryHtml(dot)}</div></div>` +
					wiki +
					credit
			);
			drawRing(dot);
			placeAt(dot);
			tooltipSel.select('.lc-close').on('click', () => unpin(true));
			// A dead Commons link (file renamed/deleted since the last refresh)
			// just drops the photo rather than showing a broken image.
			tooltipSel.select('.lc-photo img').on('error', function (this: HTMLImageElement) {
				this.closest('.lc-photo')?.remove();
				placeAt(dot);
			});
		}

		/** Open a dot's card. `takeFocus` moves keyboard focus to its close
		 *  button — right for a click, wrong for the scrolly opening it. */
		function pin(dot: Pt, takeFocus = true) {
			pinnedId = dot.row.id;
			tooltipSel
				.classed('lc-pinned', true)
				.style('pointer-events', 'auto')
				.attr('role', 'dialog')
				.attr('aria-label', dot.row.name);
			ensureLinks();
			showCard(dot);
			if (!takeFocus) return;
			(tooltipSel.select('.lc-close').node() as HTMLElement | null)?.focus({
				preventScroll: true
			});
		}

		function unpin(restoreFocus = false) {
			if (pinnedId == null) return;
			pinnedId = null;
			tooltipSel
				.classed('lc-pinned', false)
				.style('pointer-events', 'none')
				.attr('role', null)
				.attr('aria-label', null);
			clearHover();
			// Return focus to the chart so keyboard users aren't dropped at <body>.
			if (restoreFocus) (host as HTMLElement).focus({ preventScroll: true });
		}

		// After a re-render (resize, metric switch, legend filter, scrolly step)
		// keep the card on its dot, or close it if that dot is no longer shown.
		// Also opens the focused dot's card when `focusCard` asks for it, and
		// closes that card once a narrated step no longer does.
		function syncPinned() {
			const auto =
				cur.focusCard && cur.focusId != null ? dotById.get(cur.focusId) : undefined;
			if (auto && pinnedId !== auto.row.id) {
				pin(auto, false);
				return;
			}
			if (pinnedId == null) return;
			if (!auto && !cur.interactive) {
				unpin();
				return;
			}
			const dot = dotById.get(pinnedId);
			if (dot) showCard(dot);
			else unpin();
		}
		afterRender = syncPinned;

		svg
			.on('mousemove', function (event: MouseEvent) {
				// Hover is available once fields are introduced; keep it off
				// while a laureate card is pinned.
				if (!cur.interactive || pinnedId != null) return;
				ensureLinks();
				const [mx, my] = d3.pointer(event, chartArea.node());
				const hitId = nearestPoint(hitPoints, mx, my, 14);
				if (hitId == null) {
					clearHover();
					return;
				}
				svg.style('cursor', 'pointer');
				showHover(dotById.get(hitId as number)!);
				const [cx, cy] = d3.pointer(event, container.node());
				positionTooltip(container, cx, cy, { preferAbove: true });
			})
			.on('mouseleave', clearHover)
			.on('click', function (event: MouseEvent) {
				if (!cur.interactive) return;
				const [mx, my] = d3.pointer(event, chartArea.node());
				// A slightly larger radius than hover: taps are less precise.
				const hitId = nearestPoint(hitPoints, mx, my, 18);
				if (hitId == null) {
					unpin();
					return;
				}
				pin(dotById.get(hitId as number)!);
			});

		// Dismiss on Escape, or on a click anywhere outside the chart and card.
		const onKeydown = (event: KeyboardEvent) => {
			if (event.key === 'Escape' && pinnedId != null) unpin(true);
		};
		const onPointerdown = (event: PointerEvent) => {
			if (pinnedId != null && !host.contains(event.target as Node)) unpin();
		};
		document.addEventListener('keydown', onKeydown);
		document.addEventListener('pointerdown', onPointerdown);

		chart = {
			update(next) {
				const changed =
					next.metric !== cur.metric ||
					next.colorMode !== cur.colorMode ||
					next.focusId !== cur.focusId ||
					next.focusCard !== cur.focusCard ||
					next.highlightFrom !== cur.highlightFrom;
				// Close the narration's example card when its step ends, even if
				// the next step enables readers to open cards themselves.
				if (cur.focusCard && !next.focusCard && pinnedId === cur.focusId) {
					unpin();
				}
				// Returning to the opening, non-interactive steps resets any
				// legend filter the reader applied.
				if (cur.interactive && !next.interactive) {
					visible.clear();
					for (const c of PRIZE_CATEGORIES) visible.add(c);
					syncLegend();
					unpin();
					clearHover();
				}
				const wasInteractive = cur.interactive;
				cur = next;
				activeMetric = metrics.find((m) => m.key === cur.metric) ?? activeMetric;
				if (wasInteractive !== cur.interactive) syncLegendFocusable();
				render(changed || (wasInteractive && !cur.interactive));
			}
		};

		render(false);

		// Cleanup: disconnect our observer, dispatch 'remove' to trigger
		// createContainer's window-resize-listener teardown, then drop the DOM
		// we built.
		return () => {
			chart = null;
			document.removeEventListener('keydown', onKeydown);
			document.removeEventListener('pointerdown', onPointerdown);
			resizeObserver.disconnect();
			container.dispatch('remove');
			host.replaceChildren();
		};
	});
</script>

