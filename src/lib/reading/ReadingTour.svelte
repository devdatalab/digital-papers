<!--
	ReadingTour — introduces the edition's open-science features with four
	illustrated promises, then five annotated screenshots and the author's copy.

	Why it exists: several of the edition's most useful features sit off the main
	reading path and are easy to miss. A brief tour on first title-page arrival
	points them out without needing to highlight live page elements.

	Behaviour:
	  - Mounted once in +layout.svelte; open/step state lives in the `tour` store
	    so the modal survives the navigation from the title page into section 1.
	  - Built on a native <dialog> via showModal(): focus trap, Esc-to-close and an
	    inert background come for free. Esc, the backdrop and "Skip" all close it,
	    which marks the tour as seen (see tour.svelte.ts).
	  - Arrow keys step back/forward. Screenshot steps use 16:10 annotated stills
	    generated by scripts/tour-screenshots.mjs; the next image is preloaded.
	    The opening tiles use inline illustrations and accessible, editable text.
	  - Step content comes from $paper/content/tour.json; media paths there are
	    relative to static/ and resolved against SvelteKit's `base`.
	  - The dialog is centered in the viewport and scrolls internally on shorter screens.

	Upstream dependencies: the `tour` store, tour.json, and
	theme tokens from ddl-theme.css / app.css (--bg, --bg-panel, --rule, --ink, --muted, --accent,
	and the shared .btn utility).
-->
<script lang="ts">
	import { base } from '$app/paths';
	import { tour } from '$lib/state/tour.svelte';
	import tourContent from '$paper/content/tour.json';

	interface TourMedia {
		/** Image path relative to static/, e.g. "tour/paper.webp". */
		src: string;

		/** What the annotated image shows, for screen readers. */
		alt: string;
	}
	interface TourStep {
		id: string;
		title: string;
		body: string[];
		features?: { icon: 'results' | 'methods' | 'data' | 'prompt'; text: string }[];
		nextLabel?: string;
		media: TourMedia | null;
	}

	const steps = tourContent.steps as TourStep[];

	let dialog = $state<HTMLDialogElement>();
	let nextButton = $state<HTMLButtonElement>();

	let current = $derived(steps[tour.step]);
	let isLast = $derived(tour.step === steps.length - 1);
	let upcoming = $derived(steps[tour.step + 1]?.media ?? null);

	const asset = (path: string) => `${base}/${path}`;

	// Sync the native dialog with the store. Focus goes to the primary action
	// rather than showModal()'s default (the first control, "Skip").
	$effect(() => {
		if (!dialog) return;
		if (tour.open && !dialog.open) {
			dialog.showModal();
			nextButton?.focus({ preventScroll: true });
			dialog.querySelector('.card')?.scrollTo(0, 0);
		} else if (!tour.open && dialog.open) {
			dialog.close();
		}
	});

	function next() {
		if (isLast) tour.close();
		else tour.goTo(tour.step + 1);
	}
	function back() {
		if (tour.step > 0) tour.goTo(tour.step - 1);
	}

	function onKeydown(e: KeyboardEvent) {
		if (e.key === 'ArrowRight') {
			e.preventDefault();
			next();
		} else if (e.key === 'ArrowLeft') {
			e.preventDefault();
			back();
		}
	}

	// A click whose target is the <dialog> itself landed on the ::backdrop
	// (the card fills the dialog's content box), so treat it as a skip.
	function onClick(e: MouseEvent) {
		if (e.target === dialog) tour.close();
	}
</script>

<dialog
	bind:this={dialog}
	class="reading-tour ui"
	aria-labelledby="reading-tour-title"
	onclose={() => tour.open && tour.close()}
	onkeydown={onKeydown}
	onclick={onClick}
>
	{#if tour.open && current}
		<div class="card">
			<div class="media" class:welcome={current.features}>
				{#if current.features}
					<h2 id="reading-tour-title">{current.title}</h2>
					<ol class="features">
						{#each current.features as feature, i (feature.icon)}
							<li>
								<svg viewBox="0 0 64 64" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">
									{#if feature.icon === 'results'}
										<path class="icon-fill" d="M10 47 24 33 35 38 53 16v36H10Z" />
										<path d="M10 10v42h46M16 40l10-11 11 6 16-19" />
										<circle cx="26" cy="29" r="4" fill="var(--bg)" />
										<circle cx="37" cy="35" r="4" fill="var(--bg)" />
									{:else if feature.icon === 'methods'}
										<rect class="icon-fill" x="10" y="7" width="33" height="46" rx="4" />
										<path d="M18 17h17M18 25h10M18 33h8" />
										<circle cx="39" cy="38" r="12" fill="var(--bg)" />
										<path d="m48 47 9 10M34 38h10M39 33v10" />
									{:else if feature.icon === 'data'}
										<rect x="8" y="10" width="48" height="44" rx="5" />
										<path class="icon-fill" d="M8 24h48v10H8Z" />
										<path d="M8 24h48M8 34h48M8 44h48M24 24v30M41 24v30" />
										<path d="M16 17h9" />
									{:else}
										<path class="icon-fill" d="M13 10h38a5 5 0 0 1 5 5v27a5 5 0 0 1-5 5H29L16 56v-9h-3a5 5 0 0 1-5-5V15a5 5 0 0 1 5-5Z" />
										<path d="m19 23 7 6-7 6M32 35h12" />
									{/if}
								</svg>
								<span><span class="feature-number">{i + 1}.</span> {feature.text}</span>
							</li>
						{/each}
					</ol>
				{:else if current.media}
					<img src={asset(current.media.src)} alt={current.media.alt} width="1280" height="800" />
				{/if}
			</div>

			<div class="text">
				<p class="count">Step {tour.step + 1} of {steps.length}</p>
				{#if !current.features}
					<h2 id="reading-tour-title">{current.title}</h2>
				{/if}
				{#each current.body as paragraph}
					<p class="body">{paragraph}</p>
				{/each}
			</div>

			<div class="controls">
				<button type="button" class="skip" onclick={() => tour.close()}>Skip tour</button>

				<ol class="dots" aria-label="Tour steps">
					{#each steps as s, i (s.id)}
						<li>
							<button
								type="button"
								class:active={i === tour.step}
								aria-label="Go to step {i + 1}: {s.title}"
								aria-current={i === tour.step ? 'step' : undefined}
								onclick={() => tour.goTo(i)}
							></button>
						</li>
					{/each}
				</ol>

				<div class="nav">
					{#if tour.step > 0}
						<button type="button" class="back" onclick={back}>← Back</button>
					{/if}
					<button type="button" class="btn" bind:this={nextButton} onclick={next}>
						{current.nextLabel ?? (isLast ? 'Finish' : 'Next →')}
					</button>
				</div>
			</div>

			<!-- Warm the next image so stepping forward doesn't flash an empty slot. -->
			{#if upcoming}
				<img class="preload" src={asset(upcoming.src)} alt="" aria-hidden="true" />
			{/if}
		</div>
	{/if}
</dialog>

